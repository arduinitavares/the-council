// Break caught: cached home, PATH, executable identity, or controlling Deny
// is reused after current inputs change.
it("reconstructs changed HOME PATH executable and inherited Deny", () => {
  const f = fixture();
  const before = reconstructCurrentAgyInputs(f.request, budget());
  const home = join(f.root, "second-home"), bin = join(f.root, "second-bin");
  mkdirSync(join(home, ".gemini/antigravity-cli"), { recursive: true }); mkdirSync(bin);
  const executable = join(bin, "agy"), settings = join(home, ".gemini/antigravity-cli/settings.json");
  writeFileSync(executable, "second inert executable");
  const bytes = '{"permissions":{"allow":["read_file(*)"],"deny":["private(*)","private(*)"],"ask":["read_file(private)"]}}';
  writeFileSync(settings, bytes); vi.mocked(homedir).mockReturnValue(home); vi.stubEnv("HOME", home); vi.stubEnv("PATH", bin+delimiter+f.bin);
  const after = reconstructCurrentAgyInputs(f.request, budget());
  expect(after.state).toBe("present"); if (before.state !== "present" || after.state !== "present") return;
  expect(after.value.context).toMatchObject({ home, rawHome: home, environmentInputs: { PATH: bin+delimiter+f.bin } });
  expect(after.value.executable).toMatchObject({ path: executable, sha256: digest("second inert executable") });
  expect(after.sources).toContainEqual({ path: settings, kind: "file", sha256: digest(bytes) });
  const session = after.value.recipeInputs.materializations[1]!;
  expect(session.content).toBe('{"allowNonWorkspaceAccess":false,"permissions":{"allow":["read_file(*)"],"deny":["private(*)","write_file(*)","command(*)","read_url(*)","execute_url(*)","mcp(*)"],"ask":["read_file(private)"]}}');
  expect(session.path).not.toBe(before.value.recipeInputs.materializations[1]!.path);
  writeFileSync(executable, "changed at the same path");
  expect(reconstructCurrentAgyInputs(f.request, budget())).toMatchObject({ state: "present", value: { executable: { path: executable, sha256: digest("changed at the same path") } } });
});

