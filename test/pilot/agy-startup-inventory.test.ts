// Break caught: refusal, malformed JSON, or malformed controlling permissions
// is silently converted into defaults, or loses a safely acquired executable.
it.each([
  { shape: "malformed", code: "INVENTORY_JSON_INVALID", retained: false },
  { shape: "nonregular", code: "INVENTORY_NODE_TYPE", retained: false },
  { shape: "unreadable", code: "EACCES", retained: false },
  { shape: "invalid-deny", code: "AGY_RECIPE_SETTINGS_INVALID:permissions.deny", retained: true },
])("propagates guarded executable and settings failures: $shape", ({ shape, code, retained }) => {
  const f = fixture();
  if (shape === "malformed") writeFileSync(f.settings, "{broken");
  if (shape === "nonregular") { rmSync(f.settings); mkdirSync(f.settings); }
  if (shape === "invalid-deny") writeFileSync(f.settings, '{"permissions":{"deny":null}}');
  if (shape === "unreadable") {
    const open = fs.openSync;
    vi.spyOn(fs, "openSync").mockImplementation(((...args: Parameters<typeof fs.openSync>) => {
      if (String(args[0]) === f.settings) throw Object.assign(Error("fixture refusal"), { code: "EACCES", path: f.settings });
      return Reflect.apply(open, fs, args);
    }) as typeof fs.openSync);
  }
  const result = reconstructCurrentAgyInputs(f.request, budget());
  expect(result).toMatchObject({ state: "unknown", context: { home: f.home }, executable: { path: f.executable }, problems: [{ code, path: f.settings, edge: null }] });
  expect(result).not.toHaveProperty("value");
  expect(result.sources.some(source => source.path === f.settings)).toBe(retained);
});

