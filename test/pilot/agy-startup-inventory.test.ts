  const f = fixture(), shared = budget();
  const executableRead = vi.spyOn(io, "readInventoryFile"), settingsRead = vi.spyOn(io, "readInventoryJson");
  vi.spyOn(fs, "readFileSync").mockImplementation(() => { throw Error("unbounded payload read"); });
