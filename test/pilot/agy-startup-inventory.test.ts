const digest = (bytes: string) => createHash("sha256").update(bytes).digest("hex");
const budget = (): io.InventoryBudget => ({ paths: new Set(), jsonBytes: 0 });
function fixture() {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "agy-current-inputs-"))); owned.push(root);
  const home = join(root, "home"), workspace = join(root, "project"), bin = join(root, "bin");
  for (const path of [home, workspace, bin, join(home, ".gemini/antigravity-cli")]) mkdirSync(path, { recursive: true });
  const executable = join(bin, "agy"), settings = join(home, ".gemini/antigravity-cli/settings.json");
  const executableBytes = "inert fixture executable\n";
  writeFileSync(executable, executableBytes); writeFileSync(settings, "{}");
  vi.mocked(homedir).mockReturnValue(home);
  vi.stubEnv("HOME", home); vi.stubEnv("PATH", bin); vi.stubEnv("TMPDIR", root);
  vi.stubEnv("LANG", ""); vi.stubEnv("LC_ALL", undefined); vi.stubEnv("TERM", "fixture-term");
  vi.stubEnv("AGY_CLI_DISABLE_AUTO_UPDATE", "false");
  const request = { selection: incidentRoster.reviewers.gemini, version: "1.4.12", workspace };
  return { root, home, workspace, bin, executable, settings, executableBytes, request };
}

// Break caught: acquisition depends on semantic qualification or loses the
// existing builder's permission merge, generated bytes, or materializations.
it("reconstructs current AGY inputs without semantic qualification", () => {
  const f = fixture(), shared = budget();
  const acquired = reconstructCurrentAgyInputs(f.request, shared);
  expect(acquired.state).toBe("present"); if (acquired.state !== "present") return;
  expect(acquired.value.context).toEqual({ requestingWorkspace: f.workspace, executionCwd: join(f.workspace, ".council/native-packets"),
    home: f.home, rawHome: f.home, selectedAgent: "council-packet", environmentInputs: {
      PATH: f.bin, HOME: f.home, TMPDIR: f.root, LANG: "", LC_ALL: null, TERM: "fixture-term", AGY_CLI_DISABLE_AUTO_UPDATE: "true",
    } });
  expect(acquired.value.context).not.toHaveProperty("repositoryBoundary");
  expect(acquired.value.executable).toMatchObject({ path: f.executable, sha256: digest(f.executableBytes), receipt: { path: f.executable, before: { type: "file" }, after: { type: "file" } } });
  expect(acquired.value.executable).not.toHaveProperty("bytes");
  expect(acquired.value.recipeInputs).toEqual(builder.buildAgyRecipePlan({ ...f.request, executable: f.executable, legacySettings: {}, agyHookShell: null }));
  expect(acquired.sources).toEqual([{ path: f.executable, kind: "file", sha256: digest(f.executableBytes) }, { path: f.settings, kind: "file", sha256: digest("{}") }]);
  expect(acquired.ordering).toEqual([f.settings]);
  expect(shared.jsonBytes).toBe(2); expect(shared.paths.has(f.executable)).toBe(true);
  expect(process.env.AGY_CLI_DISABLE_AUTO_UPDATE).toBe("false");
});

